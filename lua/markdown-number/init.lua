local M = {}

local defaults = {
  -- Directories skipped during recursive batch processing.
  exclude_dirs = {
    [".git"] = true,
    ["node_modules"] = true,
  },
  -- Only files with this extension are processed.
  extension = "md",
  -- Print a summary after batch operations.
  notify = true,
}

local config = vim.deepcopy(defaults)

local function notify(message, level)
  if config.notify then
    vim.notify(message, level or vim.log.levels.INFO, { title = "Markdown Number" })
  end
end

local function is_fence_start(line)
  local indent, fence = line:match("^([ ]*)([`~][`~][`~]+)")
  if not fence then
    return nil
  end
  -- CommonMark fenced code blocks allow at most three leading spaces.
  if #indent > 3 then
    return nil
  end
  local char = fence:sub(1, 1)
  if fence:gsub(char, "") ~= "" then
    return nil
  end
  return char, #fence
end

local function is_fence_end(line, char, min_length)
  local indent, fence = line:match("^([ ]*)([`~][`~][`~]+)%s*$")
  if not fence or #indent > 3 then
    return false
  end
  if fence:sub(1, 1) ~= char then
    return false
  end
  return fence:gsub(char, "") == "" and #fence >= min_length
end

local function strip_number(body)
  -- Remove prefixes generated by this plugin, e.g. "1 ", "1.2 ", "1.2.3 ".
  -- Also accepts common variants such as "1. Title", "1) Title" and "1、Title".
  local stripped, count = body:gsub("^(%s*)%d+([.]%d+)*[%.、)]?%s+", "%1", 1)
  if count > 0 then
    return stripped
  end
  return body
end

local function transform_lines(lines, operation)
  local output = {}
  local counters = { 0, 0, 0, 0, 0, 0 }
  local fence_char, fence_length = nil, nil
  local changed = false

  for _, line in ipairs(lines) do
    if fence_char then
      table.insert(output, line)
      if is_fence_end(line, fence_char, fence_length) then
        fence_char, fence_length = nil, nil
      end
    else
      local start_char, start_length = is_fence_start(line)
      if start_char then
        fence_char, fence_length = start_char, start_length
        table.insert(output, line)
      else
        local hashes, spacing, body = line:match("^(%s*#+)(%s+)(.*)$")
        if hashes then
          local level = select(2, hashes:gsub("#", ""))
          if level >= 1 and level <= 6 then
            local original_body = body
            body = strip_number(body)

            if operation == "add" then
              counters[level] = counters[level] + 1
              for depth = level + 1, 6 do
                counters[depth] = 0
              end

              local parts = {}
              for depth = 1, level do
                parts[#parts + 1] = tostring(counters[depth])
              end
              local prefix = table.concat(parts, ".")
              local new_line = hashes .. spacing .. prefix .. " " .. body
              table.insert(output, new_line)
              if new_line ~= line then
                changed = true
              end
            else
              table.insert(output, hashes .. spacing .. body)
              if body ~= original_body then
                changed = true
              end
            end
          else
            table.insert(output, line)
          end
        else
          table.insert(output, line)
        end
      end
    end
  end

  return output, changed
end

local function transform_buffer(bufnr, operation)
  bufnr = bufnr or vim.api.nvim_get_current_buf()
  if not vim.api.nvim_buf_is_valid(bufnr) then
    return false, "Invalid buffer"
  end

  local lines = vim.api.nvim_buf_get_lines(bufnr, 0, -1, false)
  local updated, changed = transform_lines(lines, operation)
  if changed then
    vim.api.nvim_buf_set_lines(bufnr, 0, -1, false, updated)
  end
  return changed
end

local function transform_file(path, operation)
  local lines = vim.fn.readfile(path)
  local updated, changed = transform_lines(lines, operation)
  if changed then
    local result = vim.fn.writefile(updated, path)
    if result ~= 0 then
      return false, "Could not write file: " .. path
    end
  end
  return changed
end

local function walk_markdown_files(root)
  local files = {}
  local uv = vim.uv or vim.loop

  local function walk(directory)
    local handle = uv.fs_scandir(directory)
    if not handle then
      return
    end

    while true do
      local name, kind = uv.fs_scandir_next(handle)
      if not name then
        break
      end

      local full_path = directory .. "/" .. name
      if kind == "directory" then
        if not config.exclude_dirs[name] then
          walk(full_path)
        end
      elseif kind == "file" then
        local extension = config.extension:gsub("^%.", "")
        if name:lower():match("%." .. vim.pesc(extension) .. "$") then
          files[#files + 1] = full_path
        end
      end
    end
  end

  walk(root)
  table.sort(files)
  return files
end

local function transform_all(operation)
  local root = vim.fn.getcwd()
  local files = walk_markdown_files(root)
  local changed_count, error_count = 0, 0
  local errors = {}

  for _, path in ipairs(files) do
    local ok, changed_or_error, maybe_error = pcall(transform_file, path, operation)
    if not ok then
      error_count = error_count + 1
      errors[#errors + 1] = path .. ": " .. tostring(changed_or_error)
    elseif maybe_error then
      error_count = error_count + 1
      errors[#errors + 1] = maybe_error
    elseif changed_or_error then
      changed_count = changed_count + 1
    end
  end

  local verb = operation == "add" and "numbered" or "cleaned"
  notify(string.format(
    "Scanned %d Markdown files; %d %s; %d errors.",
    #files, changed_count, verb, error_count
  ))

  if #errors > 0 then
    for _, message in ipairs(errors) do
      vim.notify(message, vim.log.levels.ERROR, { title = "Markdown Number" })
    end
  end

  return {
    scanned = #files,
    changed = changed_count,
    errors = errors,
  }
end

function M.add()
  local changed = transform_buffer(0, "add")
  if changed then
    notify("Added heading numbers to the current buffer.")
  else
    notify("No heading changes were needed.")
  end
end

function M.remove()
  local changed = transform_buffer(0, "remove")
  if changed then
    notify("Removed heading numbers from the current buffer.")
  else
    notify("No heading numbers found.")
  end
end

function M.add_all()
  return transform_all("add")
end

function M.remove_all()
  return transform_all("remove")
end

function M.setup(opts)
  config = vim.tbl_deep_extend("force", vim.deepcopy(defaults), opts or {})

  vim.api.nvim_create_user_command("MarkdownNumberAdd", M.add, {
    desc = "Add hierarchical numbers to Markdown headings in the current buffer",
  })
  vim.api.nvim_create_user_command("MarkdownNumberRemove", M.remove, {
    desc = "Remove numbers from Markdown headings in the current buffer",
  })
  vim.api.nvim_create_user_command("MarkdownNumberAddAll", M.add_all, {
    desc = "Add hierarchical numbers to all Markdown files under the current working directory",
  })
  vim.api.nvim_create_user_command("MarkdownNumberRemoveAll", M.remove_all, {
    desc = "Remove numbers from all Markdown files under the current working directory",
  })
end

return M
